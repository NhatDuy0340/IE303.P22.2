public class Product {
    public String name;
    public double price;
    public String brand;
    public String note;
    public String imagePath;

    public Product(String name, double price, String brand, String note, String imagePath) {
        this.name = name;
        this.price = price;
        this.brand = brand;
        this.note = note;
        this.imagePath = imagePath;
    }
}
